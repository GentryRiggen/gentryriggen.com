/** A pet's online name: its typed name when that is on the list, else a seeded pick. */
export function onlineNameIdFor(name: string, petId: string): number {
  const typed = ONLINE_NAMES.findIndex(
    (n) => n.toLowerCase() === name.trim().toLowerCase()
  );
  if (typed >= 0) return typed;
  let hash = 0;
  for (let i = 0; i < petId.length; i++) {
    hash = (hash * 31 + petId.charCodeAt(i)) >>> 0;
  }
  return hash % ONLINE_NAMES.length;
}

export function onlineName(nameId: number): string {
  return ONLINE_NAMES[nameId] ?? ONLINE_NAMES[0];
}

export function isNameId(v: unknown): v is number {
  return (
    typeof v === "number" &&
    Number.isInteger(v) &&
    v >= 0 &&
    v < ONLINE_NAMES.length
  );
}
