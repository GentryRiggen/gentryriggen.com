/**
 * Writes assets/parts/index.ts: one static import per spec json, so the
 * dev-only asset studio can read every part spec without a glob. Called by
 * `assets:measure` after it adds a spec; a Jest test fails if it is stale.
 */
import { spawnSync } from "node:child_process";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

/** The text of index.ts for these spec file names (sorted by the caller). */
export function specIndexSource(files) {
  const ids = files.map((file) => file.replace(/\.json$/, ""));
  const name = (id) => id.replace(/-(\w)/g, (_, c) => c.toUpperCase()) + "Spec";
  const lines = [
    "// Generated by scripts/assets/specIndex.mjs (run by `npm run assets:measure`).",
    "// One import per assets/parts/*.json; do not edit by hand.",
    ...ids.map((id) => `import ${name(id)} from "./${id}.json";`),
    "",
    "export const PART_SPEC_LIST: readonly unknown[] = [",
    ...ids.map((id) => `  ${name(id)},`),
    "];",
    "",
  ];
  return lines.join("\n");
}

export function writeSpecIndex(root) {
  const dir = join(root, "assets", "parts");
  const files = readdirSync(dir)
    .filter((f) => f.endsWith(".json"))
    .sort();
  const path = join(dir, "index.ts");
  let before = "";
  try {
    before = readFileSync(path, "utf8");
  } catch {
    // first run
  }
  writeFileSync(path, specIndexSource(files));
  // Format it like the rest of the repo, so the format check stays green.
  spawnSync(
    process.execPath,
    [join(root, "node_modules", "prettier", "bin", "prettier.cjs"), "--write", path],
    { stdio: "ignore" }
  );
  return readFileSync(path, "utf8") !== before;
}
